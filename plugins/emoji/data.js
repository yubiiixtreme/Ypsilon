/** rank: a word that starts with the query beats one that merely contains it */
export function search(/** @type {string} */ q, limit = 8) {
  const n = q.trim().toLowerCase()
  if (!n) return []
  const scored = []
  for (const e of EMOJI) {
    const words = e.words.split(" ")
    const s = words[0] === n ? 0 : words.some((w) => w === n) ? 1 : words.some((w) => w.startsWith(n)) ? 2 : e.words.includes(n) ? 3 : -1
    if (s >= 0) scored.push({ e, s })
  }
  return scored.sort((a, b) => a.s - b.s).slice(0, limit).map((x) => x.e)
}
